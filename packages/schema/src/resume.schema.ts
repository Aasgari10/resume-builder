/**
 * Resume content model (content only; styling lives in theme.schema.ts).
 *
 * Two validation levels are built from a single definition so they never drift apart:
 *   resumeDraftSchema  lenient, used for editor autosave (empty and partial fields allowed)
 *   resumeDataSchema   strict, used for PDF export, publishing and download
 * Both levels enforce length limits, item counts and data types.
 */

import { z } from "zod";

const YEAR_MONTH = /^\d{4}-(0[1-9]|1[0-2])$/;
const YEAR_MONTH_OR_EMPTY = /^(\d{4}-(0[1-9]|1[0-2]))?$/;

function buildResumeSchemas(strict: boolean) {
  /* ───────────── Primitives ───────────── */

  // Stable item id, generated by the editor; required at both levels.
  const id = z.string().min(1);

  // Required text in strict mode; may be empty in drafts.
  const text = (min: number, max: number) =>
    strict ? z.string().min(min).max(max) : z.string().max(max);

  // http(s) URL in strict mode; any string in drafts while the user is typing.
  const url = () =>
    strict
      ? z
          .string()
          .max(500)
          .url()
          .refine((v) => /^https?:\/\//i.test(v), "لینک باید با http:// یا https:// شروع شود")
      : z.string().max(500);

  const optionalUrl = url().optional().or(z.literal(""));

  // Gregorian "YYYY-MM". Templates convert to Jalali for display when needed.
  const yearMonth = z
    .string()
    .regex(strict ? YEAR_MONTH : YEAR_MONTH_OR_EMPTY, "فرمت تاریخ باید YYYY-MM باشد");

  // current=true means the period is ongoing (no end date).
  const dateRange = z
    .object({
      start: yearMonth,
      end: yearMonth.optional(),
      current: z.boolean().default(false),
    })
    .refine((d) => !strict || d.current || !d.end || d.end >= d.start, {
      message: "تاریخ پایان نباید قبل از شروع باشد",
      path: ["end"],
    });

  /* ───────────── Basics ───────────── */

  const link = z.object({
    id,
    type: z.enum([
      "website",
      "github",
      "linkedin",
      "telegram",
      "instagram",
      "behance",
      "dribbble",
      "other",
    ]),
    label: z.string().max(50).optional(), // display label for type=other
    url: url(),
  });

  const basics = z.object({
    fullName: text(2, 80),
    jobTitle: z.string().max(100).optional(),
    avatarUrl: optionalUrl,
    email: (strict ? z.string().email().max(200) : z.string().max(200))
      .optional()
      .or(z.literal("")),
    phone: z.string().max(20).optional(),
    location: z.string().max(100).optional(),
    summary: z.string().max(1500).optional(), // "about me" paragraph
    links: z.array(link).max(10).default([]),
    // Details many Iranian employers expect on a printed resume. Shown on PDF templates only,
    // never on the public website.
    personal: z
      .object({
        birthDate: z.string().regex(/^\d{4}\/\d{2}\/\d{2}$/).optional().or(z.literal("")), // Jalali YYYY/MM/DD
        gender: z.enum(["male", "female"]).optional(),
        marital: z.enum(["single", "married"]).optional(),
        military: z.enum(["done", "exempt", "serving", "student", "none"]).optional(),
      })
      .optional(),
  });

  /* ───────────── Sections ───────────── */

  const experience = z.object({
    id,
    company: text(1, 100),
    position: text(1, 100),
    location: z.string().max(100).optional(),
    period: dateRange,
    description: z.string().max(2000).optional(),
    highlights: z.array(z.string().max(300)).max(10).default([]),
  });

  const education = z.object({
    id,
    institution: text(1, 150),
    degree: z.string().max(100).optional(),
    field: z.string().max(100).optional(), // field of study
    period: dateRange,
    grade: z.string().max(20).optional(), // GPA, free-form
    description: z.string().max(1000).optional(),
  });

  const skill = z.object({
    id,
    name: text(1, 50),
    level: z.number().int().min(1).max(5).optional(), // 1–5; templates may hide it
    category: z.string().max(50).optional(), // used for grouping
  });

  const project = z.object({
    id,
    title: text(1, 100),
    role: z.string().max(100).optional(),
    description: z.string().max(2000).optional(),
    technologies: z.array(z.string().max(40)).max(20).default([]),
    url: optionalUrl,
    repoUrl: optionalUrl,
    images: z.array(url()).max(6).default([]), // shown by portfolio templates
    period: dateRange.optional(),
  });

  // Level is required at both levels; the editor sets a default when adding.
  const language = z.object({
    id,
    name: text(1, 50),
    level: z.enum(["native", "fluent", "advanced", "intermediate", "basic"]),
  });

  const certificate = z.object({
    id,
    title: text(1, 150),
    issuer: z.string().max(100).optional(),
    date: yearMonth.optional(),
    url: optionalUrl,
  });

  // User-defined section (e.g. awards, volunteering, publications).
  const customSection = z.object({
    id,
    title: text(1, 60),
    items: z
      .array(
        z.object({
          id,
          title: text(1, 150),
          subtitle: z.string().max(150).optional(),
          date: yearMonth.optional(),
          description: z.string().max(1000).optional(),
          url: optionalUrl,
        })
      )
      .max(20)
      .default([]),
  });

  /* ───────────── Full resume ───────────── */

  const resume = z.object({
    version: z.literal(1), // bumped on breaking shape changes, for data migrations
    locale: z.enum(["fa", "en"]), // also determines text direction (RTL/LTR)
    basics,
    experience: z.array(experience).max(30).default([]),
    education: z.array(education).max(15).default([]),
    skills: z.array(skill).max(60).default([]),
    projects: z.array(project).max(30).default([]),
    languages: z.array(language).max(10).default([]),
    certificates: z.array(certificate).max(30).default([]),
    customSections: z.array(customSection).max(5).default([]),
  });

  return {
    resume,
    link,
    basics,
    experience,
    education,
    skill,
    project,
    language,
    certificate,
    customSection,
  };
}

/* ───────────── Exported schemas ───────────── */

const strictSchemas = buildResumeSchemas(true);
const draftSchemas = buildResumeSchemas(false);

/** Strict: required for PDF export, publishing and download. */
export const resumeDataSchema = strictSchemas.resume;

/** Lenient: accepted on autosave; this is what Resume.data stores. */
export const resumeDraftSchema = draftSchemas.resume;

// Strict per-section schemas, for validating a single item in isolation.
export const linkSchema = strictSchemas.link;
export const basicsSchema = strictSchemas.basics;
export const experienceSchema = strictSchemas.experience;
export const educationSchema = strictSchemas.education;
export const skillSchema = strictSchemas.skill;
export const projectSchema = strictSchemas.project;
export const languageSchema = strictSchemas.language;
export const certificateSchema = strictSchemas.certificate;
export const customSectionSchema = strictSchemas.customSection;

/* ───────────── Types ───────────── */

// Both levels share the same shape; only the validation rules differ.
export type ResumeData = z.infer<typeof resumeDataSchema>;
export type Basics = z.infer<typeof basicsSchema>;
export type Experience = z.infer<typeof experienceSchema>;
export type Education = z.infer<typeof educationSchema>;
export type Skill = z.infer<typeof skillSchema>;
export type Project = z.infer<typeof projectSchema>;
export type Language = z.infer<typeof languageSchema>;
export type Certificate = z.infer<typeof certificateSchema>;
export type CustomSection = z.infer<typeof customSectionSchema>;

// Sections that can be reordered or hidden via the theme.
export const SECTION_KEYS = [
  "experience",
  "education",
  "skills",
  "projects",
  "languages",
  "certificates",
  "customSections",
] as const;
export type SectionKey = (typeof SECTION_KEYS)[number];

/* ───────────── Helpers ───────────── */

/** Blank resume. Valid as a draft, not publishable. */
export const emptyResume = (locale: "fa" | "en" = "fa"): ResumeData => ({
  version: 1,
  locale,
  basics: { fullName: "", links: [] },
  experience: [],
  education: [],
  skills: [],
  projects: [],
  languages: [],
  certificates: [],
  customSections: [],
});

/**
 * Validates a resume against the strict schema.
 * On failure, returns issues with dotted field paths (e.g. "experience.0.company").
 */
export function checkPublishable(
  data: unknown
): { ok: true; data: ResumeData } | { ok: false; issues: { path: string; message: string }[] } {
  const result = resumeDataSchema.safeParse(data);
  if (result.success) return { ok: true, data: result.data };
  return {
    ok: false,
    issues: result.error.issues.map((i) => ({ path: i.path.join("."), message: i.message })),
  };
}
