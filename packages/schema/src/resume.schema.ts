/**
 * Resume content model (content only; styling lives in theme.schema.ts).
 *
 * Two validation levels are built from a single definition so they never drift apart:
 *   resumeDraftSchema  lenient, used for editor autosave (empty and partial fields allowed)
 *   resumeDataSchema   strict, used for PDF export, publishing and download
 * Both levels enforce length limits, item counts and data types.
 */

import { z } from "zod";

const YEAR_MONTH = /^\d{4}-(0[1-9]|1[0-2])$/;
const YEAR_MONTH_OR_EMPTY = /^(\d{4}-(0[1-9]|1[0-2]))?$/;

/** Sample pictures shipped with the app and served by the API (see SAMPLE_ASSETS_PATH in the API). */
export const SAMPLE_ASSETS_PATH = "/_assets/samples/";
/** Bumped when the pictures change, so browsers fetch the new files instead of cached ones. */
export const SAMPLE_ASSETS_VERSION = 10;
export const isSampleAsset = (v: string) => /^\/_assets\/samples\/[a-z0-9-]+\.(jpg|png|svg)(\?v=\d+)?$/.test(v);

function buildResumeSchemas(strict: boolean) {
  /* ───────────── Primitives ───────────── */

  // Stable item id, generated by the editor; required at both levels.
  const id = z.string().min(1);

  // Required text in strict mode; may be empty in drafts.
  const text = (min: number, max: number) =>
    strict ? z.string().min(min).max(max) : z.string().max(max);

  // http(s) URL in strict mode (or one of our bundled sample pictures); any string in drafts while typing.
  const url = () =>
    strict
      ? z
          .string()
          .max(500)
          .refine((v) => isSampleAsset(v) || (/^https?:\/\/\S+$/i.test(v) && z.string().url().safeParse(v).success), "لینک باید با http:// یا https:// شروع شود")
      : z.string().max(500);

  const optionalUrl = url().optional().or(z.literal(""));

  // Gregorian "YYYY-MM". Templates convert to Jalali for display when needed.
  const yearMonth = z
    .string()
    .regex(strict ? YEAR_MONTH : YEAR_MONTH_OR_EMPTY, "فرمت تاریخ باید YYYY-MM باشد");

  // current=true means the period is ongoing (no end date).
  const dateRange = z
    .object({
      start: yearMonth,
      end: yearMonth.optional(),
      current: z.boolean().default(false),
    })
    .refine((d) => !strict || d.current || !d.end || d.end >= d.start, {
      message: "تاریخ پایان نباید قبل از شروع باشد",
      path: ["end"],
    });

  /* ───────────── Basics ───────────── */

  const link = z.object({
    id,
    type: z.enum([
      "website",
      "github",
      "linkedin",
      "telegram",
      "whatsapp",
      "instagram",
      "eitaa",
      "rubika",
      "behance",
      "dribbble",
      "other",
    ]),
    label: z.string().max(50).optional(), // display label for type=other
    url: url(),
  });

  const basics = z.object({
    fullName: text(2, 80),
    jobTitle: z.string().max(100).optional(),
    avatarUrl: optionalUrl,
    email: (strict ? z.string().email().max(200) : z.string().max(200))
      .optional()
      .or(z.literal("")),
    phone: z.string().max(20).optional(),
    location: z.string().max(100).optional(),
    summary: z.string().max(1500).optional(), // "about me" paragraph
    links: z.array(link).max(10).default([]),
    // Details many Iranian employers expect on a printed resume. Shown on PDF templates only,
    // never on the public website.
    personal: z
      .object({
        birthDate: z.string().regex(/^\d{4}\/\d{2}\/\d{2}$/).optional().or(z.literal("")), // Jalali YYYY/MM/DD
        gender: z.enum(["male", "female"]).optional(),
        marital: z.enum(["single", "married"]).optional(),
        military: z.enum(["done", "exempt", "serving", "student", "none"]).optional(),
      })
      .optional(),
  });

  /* ───────────── Sections ───────────── */

  const experience = z.object({
    id,
    company: text(1, 100),
    position: text(1, 100),
    location: z.string().max(100).optional(),
    period: dateRange,
    description: z.string().max(2000).optional(),
    highlights: z.array(z.string().max(300)).max(10).default([]),
  });

  const education = z.object({
    id,
    institution: text(1, 150),
    degree: z.string().max(100).optional(),
    field: z.string().max(100).optional(), // field of study
    period: dateRange,
    grade: z.string().max(20).optional(), // GPA, free-form
    description: z.string().max(1000).optional(),
  });

  const skill = z.object({
    id,
    name: text(1, 50),
    level: z.number().int().min(1).max(5).optional(), // 1–5; templates may hide it
    category: z.string().max(50).optional(), // used for grouping
    description: z.string().max(800).optional(), // website templates that explain each skill
  });

  const project = z.object({
    id,
    title: text(1, 100),
    role: z.string().max(100).optional(),
    description: z.string().max(2000).optional(),
    technologies: z.array(z.string().max(40)).max(20).default([]),
    url: optionalUrl,
    repoUrl: optionalUrl,
    images: z.array(url()).max(6).default([]), // shown by portfolio templates
    period: dateRange.optional(),
  });

  // Level is required at both levels; the editor sets a default when adding.
  const language = z.object({
    id,
    name: text(1, 50),
    level: z.enum(["native", "fluent", "advanced", "intermediate", "basic"]),
  });

  const certificate = z.object({
    id,
    title: text(1, 150),
    issuer: z.string().max(100).optional(),
    date: yearMonth.optional(),
    url: optionalUrl,
  });

  // User-defined section (e.g. awards, volunteering, publications).
  const customSection = z.object({
    id,
    title: text(1, 60),
    items: z
      .array(
        z.object({
          id,
          title: text(1, 150),
          subtitle: z.string().max(150).optional(),
          date: yearMonth.optional(),
          description: z.string().max(1000).optional(),
          url: optionalUrl,
        })
      )
      .max(20)
      .default([]),
  });

  /* ───────────── Website-only content ───────────── */

  // Text and pictures that only multi-page website templates show (the PDF ignores them).
  const galleryItem = z.object({
    id,
    title: z.string().max(100),
    image: url(),
    description: z.string().max(500).optional(),
  });

  // What a client said about the work, and the logos of clients (shown by some templates).
  const testimonial = z.object({
    id,
    name: z.string().max(80),
    role: z.string().max(100).optional(),
    text: z.string().max(600),
    image: optionalUrl,
    rating: z.number().int().min(1).max(5).optional(), // stars shown by shop templates (5 when empty)
    hidden: z.boolean().optional(), // kept but not shown
  });
  const clientLogo = z.object({ id, name: z.string().max(80), image: url(), text: z.string().max(200).optional() }); // text: a line under the name (some shop templates)

  // Online shop (shop templates). Prices are whole tomans. Shown by shop templates only.
  const price = z.number().int().min(0).max(10_000_000_000);
  const shopCategory = z.object({ id, name: z.string().max(60), image: optionalUrl });
  const product = z.object({
    id,
    name: text(1, 120),
    categoryId: z.string().max(40).optional(),
    price,
    salePrice: price.optional(), // lower price while on sale; the regular price is shown struck through
    images: z.array(url()).max(6).default([]),
    description: z.string().max(3000).optional(),
    sizes: z.array(z.string().max(20)).max(12).optional(), // e.g. S, M, L or 38, 40
    stock: z.number().int().min(0).max(100000).optional(), // left out: not tracked; 0: sold out
    badge: z.string().max(20).optional(), // small label on the picture, e.g. "حراج" or "جدید"
    featured: z.boolean().optional(), // shown in the home page's "newest trends" list
    seoTitle: z.string().max(70).optional(), // the product page's title in search results
    seoDescription: z.string().max(160).optional(), // and its description there
    hidden: z.boolean().optional(), // kept in the panel but not shown on the site
    specs: z.array(z.object({ label: z.string().max(40), value: z.string().max(80) })).max(12).optional(), // e.g. brand, weight, size
    optionLabel: z.string().max(30).optional(), // what the "sizes" choices are called, e.g. "رنگ" or "حافظه"
    saleEndsAt: z.string().max(40).optional(), // ISO date; the sale price shows a countdown until then
    // Choices such as colour and size (at most two), and the combinations with their own price/stock.
    options: z
      .array(z.object({ name: z.string().max(30), values: z.array(z.object({ label: z.string().min(1).max(30), color: z.string().regex(/^#[0-9a-fA-F]{6}$/).optional() })).max(12) }))
      .max(2)
      .optional(),
    variants: z.array(z.object({ key: z.string().max(70), price: price.optional(), stock: z.number().int().min(0).max(100000).optional() })).max(144).optional(),
    trashed: z.boolean().optional(), // in the panel's trash (also hidden); can be restored
  });
  const perk = z.object({ id, title: z.string().max(60), text: z.string().max(200).optional() });
  // One picture of the home page slider, with its own heading and line of text.
  const slide = z.object({ id, title: z.string().max(120).optional(), text: z.string().max(400).optional(), image: optionalUrl });
  const shop = z.object({
    categories: z.array(shopCategory).max(30).default([]),
    products: z.array(product).max(300).default([]),
    announcements: z.array(z.string().max(100)).max(4).optional(), // the dark strip at the very top
    heroTitle: z.string().max(120).optional(),
    heroText: z.string().max(400).optional(),
    heroImage: optionalUrl,
    slides: z.array(slide).max(5).optional(), // home page slider; when empty the hero texts above make one slide
    newTitle: z.string().max(120).optional(), // the tall "new arrivals" card with every category
    newText: z.string().max(300).optional(),
    newImage: optionalUrl,
    discoverTitle: z.string().max(120).optional(), // the card listing a few products
    discoverImage: optionalUrl,
    promoTitle: z.string().max(120).optional(), // the dark offer card
    promoText: z.string().max(200).optional(),
    lookTitle: z.string().max(120).optional(), // "Inspire your wardrobe"
    lookText: z.string().max(200).optional(),
    lookImage: optionalUrl,
    lookProductId: z.string().max(40).optional(), // the product shown beside the big picture
    // Points on the big picture; picking one shows its product in the card. x and y are percentages.
    lookSpots: z.array(z.object({ id, productId: z.string().max(40), x: z.number().min(0).max(100), y: z.number().min(0).max(100) })).max(4).optional(),
    trendImage: optionalUrl,
    bandItems: z.array(z.string().max(60)).max(6).optional(), // the moving dark band
    perks: z.array(perk).max(4).optional(),
    // Discount codes customers type at checkout.
    coupons: z
      .array(
        z.object({
          id,
          code: z.string().trim().min(2).max(30),
          percent: z.number().int().min(1).max(100).optional(), // either a percent…
          amount: price.optional(), // …or a fixed amount off
          maxDiscount: price.optional(), // cap for percent codes
          minTotal: price.optional(), // only for carts from this amount
          startsAt: z.string().max(40).optional(),
          endsAt: z.string().max(40).optional(),
          // Only for these products / categories (both empty: the whole cart).
          productIds: z.array(z.string().max(40)).max(200).optional(),
          categoryIds: z.array(z.string().max(40)).max(50).optional(),
          usageLimit: z.number().int().min(1).max(100000).optional(),
          used: z.number().int().min(0).optional(), // counted by the server on each order
          active: z.boolean().optional(),
        }),
      )
      .max(50)
      .optional(),
    heroKicker: z.string().max(120).optional(), // short line above the hero heading
    // Ad pictures between sections; some templates write the kicker, title and text over the picture.
    banners: z
      .array(z.object({ id, image: optionalUrl, link: optionalUrl, wide: z.boolean().optional(), title: z.string().max(80).optional(), kicker: z.string().max(40).optional(), text: z.string().max(160).optional(), hidden: z.boolean().optional() }))
      .max(12)
      .optional(),
    bestTitle: z.string().max(120).optional(),
    bestText: z.string().max(200).optional(),
    discountTitle: z.string().max(120).optional(),
    showcaseTitle: z.string().max(120).optional(), // a section for one chosen category
    showcaseText: z.string().max(200).optional(),
    showcaseCategoryId: z.string().max(40).optional(),
    // Comments of signed-in customers show at once instead of waiting for the owner's approval.
    reviewsAutoApprove: z.boolean().optional(),
    newsletterTitle: z.string().max(120).optional(),
    newsletterText: z.string().max(200).optional(),
    shippingFee: price.optional(), // added to every order; 0 or empty: free
    freeShippingFrom: price.optional(), // orders from this amount ship free
    // Questions and answers (the "/faq" page) and simple text pages such as "about us" or "terms".
    faqTitle: z.string().max(120).optional(),
    faq: z.array(z.object({ id, q: z.string().max(200), a: z.string().max(1500) })).max(30).optional(),
    pages: z
      .array(z.object({ id, slug: z.string().regex(/^[a-z0-9-]{1,30}$/), title: z.string().max(80), text: z.string().max(8000), hidden: z.boolean().optional() }))
      .max(8)
      .optional(),
    // Blog posts (the "/blog" page of templates that have one); managed in the shop panel.
    posts: z
      .array(
        z.object({
          id,
          title: text(1, 160),
          image: optionalUrl,
          date: z.string().max(40).optional(), // ISO date shown under the title
          author: z.string().max(60).optional(),
          category: z.string().max(40).optional(),
          excerpt: z.string().max(400).optional(), // the short text in the list; the start of the text when empty
          text: z.string().max(20000).default(""),
          hidden: z.boolean().optional(),
        }),
      )
      .max(60)
      .optional(),
    paymentNote: z.string().max(600).optional(), // how to pay for now (card-to-card, on delivery…)
    orderNote: z.string().max(300).optional(), // shown after an order is placed
  });

  const site = z.object({
    tagline: z.string().max(200).optional(), // one or two lines under the name; the summary is used when empty
    ctaPrimary: z.string().max(30).optional(), // hero button to the work
    ctaSecondary: z.string().max(30).optional(), // hero button to contact
    contactVia: z.enum(["email", "whatsapp", "telegram", "phone", "about"]).optional(), // where that button leads
    aboutTitle: z.string().max(120).optional(),
    aboutText: z.string().max(4000).optional(),
    aboutImage: optionalUrl,
    aboutCaption: z.string().max(80).optional(),
    gallery: z.array(galleryItem).max(40).default([]),
    testimonials: z.array(testimonial).max(20).optional(),
    clients: z.array(clientLogo).max(30).optional(),
    hiddenPages: z.array(z.string().max(20)).max(10).optional(), // menu pages the user switched off, e.g. "/gallery"
    hiddenBlocks: z.array(z.string().max(30)).max(30).optional(), // template sections the user switched off
    clearedFields: z.array(z.string().max(40)).max(60).optional(), // fields emptied on purpose: the preview shows no sample there
    signatureImage: optionalUrl,
    // Extra texts and pictures used by some templates (e.g. "Aseman"); each template uses what it needs.
    heroImage: optionalUrl,
    accentImage: optionalUrl,
    styleTitle: z.string().max(120).optional(),
    styleText: z.string().max(3000).optional(),
    contactTitle: z.string().max(120).optional(),
    contactText: z.string().max(1000).optional(),
    bandText: z.string().max(200).optional(),
    address: z.string().max(200).optional(),
    contactNote: z.string().max(500).optional(),
    mapUrl: optionalUrl, // a map link (Google Maps, Neshan, Balad) for directions
    shop: shop.optional(),
  });

  /* ───────────── Full resume ───────────── */

  const resume = z.object({
    version: z.literal(1), // bumped on breaking shape changes, for data migrations
    locale: z.enum(["fa", "en"]), // also determines text direction (RTL/LTR)
    basics,
    experience: z.array(experience).max(30).default([]),
    education: z.array(education).max(15).default([]),
    skills: z.array(skill).max(60).default([]),
    projects: z.array(project).max(30).default([]),
    languages: z.array(language).max(10).default([]),
    certificates: z.array(certificate).max(30).default([]),
    customSections: z.array(customSection).max(5).default([]),
    site: site.optional(),
  });

  return {
    resume,
    link,
    basics,
    experience,
    education,
    skill,
    project,
    language,
    certificate,
    customSection,
    site,
    galleryItem,
    product,
    shop,
  };
}

/* ───────────── Exported schemas ───────────── */

const strictSchemas = buildResumeSchemas(true);
const draftSchemas = buildResumeSchemas(false);

/** Strict: required for PDF export, publishing and download. */
export const resumeDataSchema = strictSchemas.resume;

/** Lenient: accepted on autosave; this is what Resume.data stores. */
export const resumeDraftSchema = draftSchemas.resume;

// Strict per-section schemas, for validating a single item in isolation.
export const linkSchema = strictSchemas.link;
export const basicsSchema = strictSchemas.basics;
export const experienceSchema = strictSchemas.experience;
export const educationSchema = strictSchemas.education;
export const skillSchema = strictSchemas.skill;
export const projectSchema = strictSchemas.project;
export const languageSchema = strictSchemas.language;
export const certificateSchema = strictSchemas.certificate;
export const customSectionSchema = strictSchemas.customSection;
export const siteContentSchema = draftSchemas.site;

/* ───────────── Types ───────────── */

// Both levels share the same shape; only the validation rules differ.
export type ResumeData = z.infer<typeof resumeDataSchema>;
export type Basics = z.infer<typeof basicsSchema>;
export type Experience = z.infer<typeof experienceSchema>;
export type Education = z.infer<typeof educationSchema>;
export type Skill = z.infer<typeof skillSchema>;
export type Project = z.infer<typeof projectSchema>;
export type Language = z.infer<typeof languageSchema>;
export type Certificate = z.infer<typeof certificateSchema>;
export type CustomSection = z.infer<typeof customSectionSchema>;
export type SiteContent = z.infer<typeof siteContentSchema>;
export type GalleryItem = SiteContent["gallery"][number];
export const productSchema = strictSchemas.product;
export type Shop = z.infer<typeof strictSchemas.shop>;
export type Product = z.infer<typeof productSchema>;

// Sections that can be reordered or hidden via the theme.
export const SECTION_KEYS = [
  "experience",
  "education",
  "skills",
  "projects",
  "languages",
  "certificates",
  "customSections",
] as const;
export type SectionKey = (typeof SECTION_KEYS)[number];

/* ───────────── Helpers ───────────── */

/** Blank resume. Valid as a draft, not publishable. */
export const emptyResume = (locale: "fa" | "en" = "fa"): ResumeData => ({
  version: 1,
  locale,
  basics: { fullName: "", links: [] },
  experience: [],
  education: [],
  skills: [],
  projects: [],
  languages: [],
  certificates: [],
  customSections: [],
});

/**
 * Validates a resume against the strict schema.
 * On failure, returns issues with dotted field paths (e.g. "experience.0.company").
 */
export function checkPublishable(
  data: unknown
): { ok: true; data: ResumeData } | { ok: false; issues: { path: string; message: string }[] } {
  const result = resumeDataSchema.safeParse(data);
  if (result.success) return { ok: true, data: result.data };
  return {
    ok: false,
    issues: result.error.issues.map((i) => ({ path: i.path.join("."), message: i.message })),
  };
}
